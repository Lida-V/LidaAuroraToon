"""Renders the README sample images on primitives (no character model).

blender -b --python tools/render_readme.py -- <output folder>
Also writes docs/INPUTS.md from the node group inputs.
"""
import bpy, sys, os, math
sys.dont_write_bytecode = True
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'blender'))
from lida_aurora_toon import shader
from lida_aurora_toon.presets import PRESETS

out = sys.argv[sys.argv.index('--') + 1]
os.makedirs(out, exist_ok=True)
scene = bpy.context.scene
for o in list(scene.objects):
    bpy.data.objects.remove(o)
scene.render.engine = 'BLENDER_EEVEE'
scene.view_settings.view_transform = 'Standard'
scene.render.fps = 24
world = bpy.data.worlds.new('ReadmeWorld')
world.use_nodes = True
world.node_tree.nodes['Background'].inputs[0].default_value = (0.035, 0.075, 0.13, 1)
world.node_tree.nodes['Background'].inputs[1].default_value = 1.0
scene.world = world
sun = shader.ensure_sun(scene)

ITEMS = [('shell', (0.72, 0.62, 0.90)), ('scale', (0.78, 0.56, 0.88)), ('pearl', (0.95, 0.92, 0.96)),
         ('gem', (0.55, 0.75, 0.95)), ('fin', (0.80, 0.78, 0.95)), ('hair_softglow', (0.95, 0.62, 0.74))]
for i, (preset, col) in enumerate(ITEMS):
    x = (i - (len(ITEMS) - 1) / 2) * 0.27
    if preset == 'fin':
        bpy.ops.mesh.primitive_torus_add(major_radius=0.075, minor_radius=0.032, major_segments=64, minor_segments=24, location=(x, 0, 0), rotation=(math.radians(70), 0, 0.3))
    elif preset == 'hair_softglow':
        bpy.ops.mesh.primitive_torus_add(major_radius=0.07, minor_radius=0.045, major_segments=64, minor_segments=32, location=(x, 0, 0), rotation=(math.radians(90), 0, 0))
    else:
        bpy.ops.mesh.primitive_uv_sphere_add(segments=64, ring_count=32, radius=0.1, location=(x, 0, 0))
    ob = bpy.context.object
    bpy.ops.object.shade_smooth()
    mat = bpy.data.materials.new('Sample_' + preset)
    mat.use_nodes = True
    next(n for n in mat.node_tree.nodes if n.type == 'BSDF_PRINCIPLED').inputs['Base Color'].default_value = (*col, 1)
    ob.data.materials.append(mat)
    kw = {}
    if preset == 'fin':
        shader.bake_thickness(ob, full_thickness=0.05)
        kw['thickness_attribute'] = shader.THICKNESS_ATTR
    shader.apply_material(mat, preset, sun, **kw)
shader.ensure_glow(scene, strength=1.0, size=0.7)

cd = bpy.data.cameras.new('ReadmeCam')
cam = bpy.data.objects.new('ReadmeCam', cd)
scene.collection.objects.link(cam)
scene.camera = cam
cd.type = 'ORTHO'
cd.ortho_scale = 1.7
cam.location = (0, -3, 0.0)
cam.rotation_euler = (math.radians(90), 0, 0)
scene.render.resolution_x, scene.render.resolution_y = 1700, 320
for f in (1, 72, 144):
    scene.frame_set(f)
    scene.render.filepath = os.path.join(out, 'presets_f%03d.png' % f)
    bpy.ops.render.render(write_still=True)

lines = ['# Inputs of the LidaAuroraToon node / 入力の一覧', '',
         'Generated by `tools/render_readme.py` from version %s. %d inputs.' % (shader.VERSION, len(shader.GROUP_INPUTS)), '',
         '| Input | Default | 説明 |', '| --- | --- | --- |']
for name, typ, dv, desc in shader.GROUP_INPUTS:
    d = '(%s)' % ', '.join('%.3g' % v for v in dv) if isinstance(dv, (tuple, list)) else ('%.4g' % dv if isinstance(dv, float) else str(dv))
    lines.append('| `%s` | %s | %s |' % (name, d, desc.replace('|', '/')))
lines += ['', '## Presets', '', ', '.join('`%s`' % k for k in PRESETS), '',
          '## Master sliders (object `%s`)' % shader.CONTROL, '', ', '.join('`%s`' % k for k in shader.LEVELS) + ', `Glow`', '']
open(os.path.join(ROOT, 'docs', 'INPUTS.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('README_RENDER_DONE')
