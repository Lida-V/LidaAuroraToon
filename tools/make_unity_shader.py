"""Write the generated parts of the Unity package from the Blender inputs and presets.

blender -b --factory-startup --python tools/make_unity_shader.py

Writes (under unity/com.github.lida-v.lidaauroratoon/Runtime/):
  Shaders/LidaAuroraToon.shader        the property list = the node group inputs
  Shaders/LidaAuroraToonInput.hlsl     UnityPerMaterial and AuroraLoadParams()
  Presets/LidaAuroraToonPresets.json   every preset, colours in linear values
So the Unity names and defaults cannot drift from Blender's.
"""
import os, sys, re, json

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, 'blender'))
from lida_aurora_toon import shader as S          # noqa: E402
from lida_aurora_toon.presets import PRESETS, TRANSLUCENT   # noqa: E402

PKG = os.path.join(ROOT, 'unity', 'com.github.lida-v.lidaauroratoon', 'Runtime')
# inputs that the Unity side feeds another way (textures, vertex colour, object position)
SKIP = {'Base Color', 'Shade Texture', 'Normal Override', 'Normal Override Mix', 'Aurora Coord', 'Alpha'}


def pname(n):
    return '_' + re.sub(r'[^A-Za-z0-9]', '', n)


def fname(n):
    return re.sub(r'[^A-Za-z0-9]', '', n)


def to_srgb(x):
    if x <= 0.0031308:
        return 12.92 * x
    return 1.055 * (x ** (1 / 2.4)) - 0.055


def fmt(x):
    return ('%.6f' % x).rstrip('0').rstrip('.') if x != int(x) else '%d' % x


inputs = [(n, t, dv, desc) for (n, t, dv, desc) in S.GROUP_INPUTS if n not in SKIP]

# ---------------- Input.hlsl ----------------
cb, st, ld = [], [], []
for n, t, dv, desc in inputs:
    if t == S.C:
        cb.append('    float4 %s;' % pname(n)); st.append('    float3 %s;' % fname(n)); ld.append('    m.%s = %s.rgb;' % (fname(n), pname(n)))
    elif t == S.V3:
        cb.append('    float4 %s;' % pname(n)); st.append('    float3 %s;' % fname(n)); ld.append('    m.%s = %s.xyz;' % (fname(n), pname(n)))
    else:
        cb.append('    float %s;' % pname(n)); st.append('    float %s;' % fname(n)); ld.append('    m.%s = %s;' % (fname(n), pname(n)))
EXTRA_CB = '''    float4 _BaseMap_ST;
    float4 _BaseColor;
    float4 _ShadeMapColor;
    float  _Alpha;
    float  _UseAlphaMap;
    float  _VertexThickness;
    float  _VertexOcclusion;
    float  _VertexMask;
    float  _VertexAlpha;
    float4 _IriBasePhaseThick;
    float4 _AuroraStrengthThick;
    float  _AuroraCoordUV;
    float  _UnlitDarkness;
    float  _AdditionalLights;
    float  _Surface;
    float  _Cull;
    float  _SrcBlend;
    float  _DstBlend;
    float  _ZWrite;'''
hlsl = '''// SPDX-License-Identifier: LicenseRef-Lida-Attribution-1.1
// Copyright (c) 2026 Lida
// GENERATED by tools/make_unity_shader.py from blender/lida_aurora_toon/shader.py %s - do not edit by hand.
#ifndef LIDA_AURORA_TOON_INPUT_INCLUDED
#define LIDA_AURORA_TOON_INPUT_INCLUDED

CBUFFER_START(UnityPerMaterial)
%s
%s
CBUFFER_END

struct AuroraParams
{
%s
};

AuroraParams AuroraLoadParams()
{
    AuroraParams m;
%s
    return m;
}

#endif // LIDA_AURORA_TOON_INPUT_INCLUDED
''' % (S.VERSION, EXTRA_CB, '\n'.join(cb), '\n'.join(st), '\n'.join(ld))

# ---------------- .shader ----------------
props = []
groups = {'Shade Tint 1': 'Toon shade', 'Lit Tint': 'Light rim gloss', 'Unlit': 'Tone', 'Base Lift': 'Base colour',
          'Effect Mask': 'Nacre iridescence', 'Aurora Strength': 'Aurora', 'Opacity': 'Translucency', 'Glint Strength': 'Glint outline light'}
for n, t, dv, desc in inputs:
    if n in groups:
        props.append('        [Header(%s)]' % groups[n])
    label = n.replace('"', "'")
    if t == S.C:
        hdr = '[HDR] ' if max(dv[:3]) > 1.0 or n in ('Lit Tint', 'Aurora Tint', 'Rim Color', 'Spec Color', 'Transmit Color') else ''
        c = [to_srgb(x) if x <= 1.0 else to_srgb(1.0) * (x ** (1 / 2.2)) for x in dv[:3]]
        props.append('        %s%s ("%s", Color) = (%s, %s, %s, 1)' % (hdr, pname(n), label, fmt(c[0]), fmt(c[1]), fmt(c[2])))
    elif t == S.V3:
        props.append('        %s ("%s", Vector) = (%s, %s, %s, 0)' % (pname(n), label, fmt(dv[0]), fmt(dv[1]), fmt(dv[2])))
    else:
        props.append('        %s ("%s", Float) = %s' % (pname(n), label, fmt(dv)))

SHADER = '''// SPDX-License-Identifier: LicenseRef-Lida-Attribution-1.1
// Copyright (c) 2026 Lida
// ============================================================================
// LidaAuroraToon for Unity URP - soft toon with nacre iridescence, aurora light,
// translucency and an outline glint. The same math as the Blender node group
// (LidaAuroraToonCore.hlsl). Tested with Unity 6000.6 / URP 17.6, Linear colour
// space, Forward+, D3D11.
// GENERATED by tools/make_unity_shader.py (Blender %s) - edit the generator, not this file.
// ============================================================================
Shader "LidaAuroraToon/Toon"
{
    Properties
    {
        [Header(Textures and vertex colour)]
        [MainTexture] _BaseMap ("Base Map (sRGB, UV0)", 2D) = "white" {}
        [MainColor] _BaseColor ("Base Color (multiplies the map)", Color) = (1, 1, 1, 1)
        _ShadeMap ("Shade Map (sRGB; used when Use Shade Texture = 1)", 2D) = "white" {}
        _ShadeMapColor ("Shade Map Color", Color) = (1, 1, 1, 1)
        _Alpha ("Alpha (Blender: Alpha input)", Float) = 1
        [Toggle] _UseAlphaMap ("Use Alpha Map (R)", Float) = 0
        [NoScaleOffset] _AlphaMap ("Alpha Map (linear, R)", 2D) = "white" {}
        [Toggle] _VertexThickness ("Thickness from vertex colour R", Float) = 0
        [Toggle] _VertexOcclusion ("Occlusion from vertex colour G", Float) = 0
        [Toggle] _VertexMask ("Effect Mask from vertex colour B", Float) = 0
        [Toggle] _VertexAlpha ("Alpha x vertex colour A", Float) = 0
        _IriBasePhaseThick ("Iri Base Phase by thickness (x on, y at 0, z at 1)", Vector) = (0, 0, 0, 0)
        _AuroraStrengthThick ("Aurora Strength by thickness (x on, y at 0, z at 1)", Vector) = (0, 0, 0, 0)
        [Toggle] _AuroraCoordUV ("Aurora coordinate = UV (off = object space)", Float) = 0
        _UnlitDarkness ("Unlit Darkness (Blender: 0.5)", Float) = 0.5
        [Toggle] _AdditionalLights ("Additional Lights", Float) = 1
%s
        [Header(Render state)]
        [Enum(Opaque, 0, Transparent, 1)] _Surface ("Surface", Float) = 0
        [Enum(UnityEngine.Rendering.CullMode)] _Cull ("Cull", Float) = 0
        [HideInInspector] _SrcBlend ("Src Blend", Float) = 1
        [HideInInspector] _DstBlend ("Dst Blend", Float) = 0
        [HideInInspector] _ZWrite ("Z Write", Float) = 1
    }

    SubShader
    {
        Tags { "RenderPipeline" = "UniversalPipeline" "RenderType" = "Opaque" "Queue" = "Geometry" }
        LOD 300

        // see-through presets only (turned on by LidaAuroraToonMaterials.SetupRenderState): write the
        // depth of this object first, so only its nearest wall is shaded (EEVEE: Transparency Overlap off)
        Pass
        {
            Name "AuroraDepthPrepass"
            Tags { "LightMode" = "SRPDefaultUnlit" }
            Cull [_Cull]
            ZWrite On
            ZTest LEqual
            ColorMask 0

            HLSLPROGRAM
            #pragma target 4.5
            #pragma multi_compile_instancing
            #pragma vertex AuroraDepthVertex
            #pragma fragment AuroraDepthFragment
            #include "LidaAuroraToonPasses.hlsl"
            ENDHLSL
        }

        Pass
        {
            Name "AuroraForward"
            Tags { "LightMode" = "UniversalForward" }
            Cull [_Cull]
            Blend [_SrcBlend] [_DstBlend]
            ZWrite [_ZWrite]
            ZTest LEqual

            HLSLPROGRAM
            #pragma target 4.5
            #pragma multi_compile_instancing
            #pragma vertex AuroraForwardVertex
            #pragma fragment AuroraForwardFragment
            #pragma multi_compile _ _MAIN_LIGHT_SHADOWS _MAIN_LIGHT_SHADOWS_CASCADE _MAIN_LIGHT_SHADOWS_SCREEN
            #pragma multi_compile_fragment _ _SHADOWS_SOFT _SHADOWS_SOFT_LOW _SHADOWS_SOFT_MEDIUM _SHADOWS_SOFT_HIGH
            #pragma multi_compile _ _ADDITIONAL_LIGHTS
            #pragma multi_compile_fragment _ _ADDITIONAL_LIGHT_SHADOWS
            #pragma multi_compile _ _CLUSTER_LIGHT_LOOP
            #pragma multi_compile_fog
            #define LIDA_AURORA_FORWARD 1
            #include "LidaAuroraToonPasses.hlsl"
            ENDHLSL
        }

        Pass
        {
            Name "ShadowCaster"
            Tags { "LightMode" = "ShadowCaster" }
            Cull [_Cull]
            ZWrite On
            ZTest LEqual
            ColorMask 0

            HLSLPROGRAM
            #pragma target 4.5
            #pragma multi_compile_instancing
            #pragma multi_compile_vertex _ _CASTING_PUNCTUAL_LIGHT_SHADOW
            #pragma vertex AuroraDepthVertex
            #pragma fragment AuroraDepthFragment
            #define LIDA_AURORA_SHADOW 1
            #include "LidaAuroraToonPasses.hlsl"
            ENDHLSL
        }

        Pass
        {
            Name "DepthOnly"
            Tags { "LightMode" = "DepthOnly" }
            Cull [_Cull]
            ZWrite On
            ColorMask R

            HLSLPROGRAM
            #pragma target 4.5
            #pragma multi_compile_instancing
            #pragma vertex AuroraDepthVertex
            #pragma fragment AuroraDepthFragment
            #include "LidaAuroraToonPasses.hlsl"
            ENDHLSL
        }

        Pass
        {
            Name "DepthNormals"
            Tags { "LightMode" = "DepthNormals" }
            Cull [_Cull]
            ZWrite On

            HLSLPROGRAM
            #pragma target 4.5
            #pragma multi_compile_instancing
            #pragma vertex AuroraDepthVertex
            #pragma fragment AuroraDepthNormalsFragment
            #include "LidaAuroraToonPasses.hlsl"
            ENDHLSL
        }
    }

    FallBack "Hidden/Universal Render Pipeline/FallbackError"
}
''' % (S.VERSION, '\n'.join(props))

# ---------------- presets ----------------
defaults = {pname(n): (list(dv[:3]) if t in (S.C, S.V3) else dv) for (n, t, dv, desc) in inputs}
types = {pname(n): ('color' if t == S.C else 'vector' if t == S.V3 else 'float') for (n, t, dv, desc) in inputs}
pres = {}
for name, vals in PRESETS.items():
    d = {}
    for k, v in vals.items():
        if k in SKIP:
            continue
        d[pname(k)] = list(v[:3]) if isinstance(v, (tuple, list)) else v
    pres[name] = {'values': d, 'translucent': name in TRANSLUCENT}
presets_json = {'version': S.VERSION, 'note': 'colours are linear (scene-referred) values, as in Blender',
                'inputs': [{'blender': n, 'property': pname(n), 'type': types[pname(n)], 'default': defaults[pname(n)], 'description': desc}
                           for (n, t, dv, desc) in inputs],
                'presets': pres,
                'levels': {k: {'default': v[1], 'max': v[2]} for k, v in S.LEVELS.items()}}

os.makedirs(os.path.join(PKG, 'Shaders'), exist_ok=True)
os.makedirs(os.path.join(PKG, 'Presets'), exist_ok=True)
for path, text in ((os.path.join(PKG, 'Shaders', 'LidaAuroraToonInput.hlsl'), hlsl),
                   (os.path.join(PKG, 'Shaders', 'LidaAuroraToon.shader'), SHADER)):
    with open(path, 'w', encoding='ascii', newline='\n') as f:
        f.write(text)
with open(os.path.join(PKG, 'Presets', 'LidaAuroraToonPresets.json'), 'w', encoding='utf-8', newline='\n') as f:
    json.dump(presets_json, f, indent=1, ensure_ascii=False)
print('GENERATED', len(inputs), 'inputs,', len(pres), 'presets')
